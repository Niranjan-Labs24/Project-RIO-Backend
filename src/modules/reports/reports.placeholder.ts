// Real generators (see reports.service.ts#generateContent + generators/):
//   RPT01 Individual Survey · RPT02 Collective · RPT03/RPT09 Top-Priority ·
//   RPT04 Sector · RPT06 Region · RPT10 Data-Quality · RPT12 Sharing Status ·
//   RPT13 Executive · RPT14 Village · RPT15 Survey & Dashboard Report ·
//   RPT16 Combined Evidence & Score · RPT17 Evidence Document-Based
// Everything else is still placeholder.
export type PlaceholderReportType = Exclude<
  ReportTypeCode,
  | "RPT01" | "RPT02" | "RPT03" | "RPT04" | "RPT06" | "RPT09" | "RPT10"
  | "RPT12" | "RPT13" | "RPT14" | "RPT15" | "RPT16" | "RPT17"
>;
export const PLACEHOLDER_REPORT_TYPES: PlaceholderReportType[] = [
  "RPT05", "RPT07", "RPT08", "RPT11",
];

/** Narrows a ReportTypeCode to the still-placeholder set — lets the caller tell
 *  "no generator yet, by design" apart from "generator route is missing". */
export function isPlaceholderReportType(code: ReportTypeCode): code is PlaceholderReportType {
  return (PLACEHOLDER_REPORT_TYPES as ReportTypeCode[]).includes(code);
}

// Audit/metadata header (RIO-NFR-008) — every field renders conditionally
// since reviewedBy/reviewedAt are null on any report not yet reviewed, and
// studyTitle is null for org-wide/non-study-scoped report types (see
// REPORT_TYPE_META.requiresStudyId).
export interface ExportAuditMeta {
  generatedAt: string;
  status: string;
  studyTitle: string | null;
  generatedByName: string | null;
  officerConfirmedByName: string | null;
  officerConfirmedAt: string | null;
  reviewedByName: string | null;
  // Reviewer's role name (e.g. "Reviewer/Approver" vs "Center Supervisor") —
  // shown in the audit trail for clarity on who approved, in what capacity.
  reviewedByRole: string | null;
  reviewedAt: string | null;
  archivedAt: string | null;
  // RIO-RPT-001 acceptance criterion 5: the methodology/data version the report
  // was generated against is stamped alongside the timestamp and the generating
  // user. Without it a figure cannot be reconciled after the fact — a reader
  // has no way to know which version of the scoring rules produced it, so a
  // later methodology change makes every archived report unverifiable.
  //
  // Resolved from the report content's own header (the version the generator
  // actually used), never from the study's current version, which may have
  // moved on since. Null only when the content carries no header at all.
  methodologyVersion: string | null;
}

// Compact, human-readable stamp (e.g. "22 Jul 2026, 10:30") instead of raw ISO.
function fmtStamp(iso: string, locale: AppLocale): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  // Locale-formatted, but the CALENDAR stays Gregorian and the digits stay
  // Western in both languages. Both are open client questions (RIO-I18N-003
  // §11) — Hijri dates and Arabic-Indic numerals are plausible requirements for
  // NCNP output and neither is a safe default to assume. `ar` here rather than
  // `ar-SA`, because `ar-SA` selects the Islamic calendar in Node's ICU and
  // would silently answer that question the wrong way round.
  return d.toLocaleString(locale === "ar" ? "ar" : "en-GB", {
    day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit",
    calendar: "gregory", numberingSystem: "latn",
    // Pinned to a 24-hour clock in BOTH languages. Arabic's default is 12-hour
    // with ص/م, which would have made the same instant read as "04:00 م" in one
    // edition and "16:00" in the other — two files from one approval, showing
    // different-looking timestamps, is exactly the reconciliation problem the
    // export-time design exists to avoid.
    hourCycle: "h23",
  });
}

function auditMetaLines(
  meta: ExportAuditMeta,
  locale: AppLocale,
): Array<{ field: string; value: string }> {
  const t = translator(locale);
  const rows: Array<{ field: string; value: string }> = [
    { field: t("audit.generatedAt"), value: fmtStamp(meta.generatedAt, locale) },
    { field: t("audit.status"), value: meta.status },
  ];
  if (meta.studyTitle) rows.push({ field: t("audit.study"), value: meta.studyTitle });
  if (meta.generatedByName) rows.push({ field: t("audit.generatedBy"), value: meta.generatedByName });
  // Sits immediately after "Generated By" so the three AC-5 facts — when, who,
  // against which methodology — read as one provenance line.
  if (meta.methodologyVersion) rows.push({ field: t("audit.methodologyVersion"), value: meta.methodologyVersion });
  // Which language edition this file is. Belongs with the provenance facts for
  // the same reason the methodology version does: a shared file must state what
  // it is without the reader having to open the other one to compare
  // (RIO-I18N-003 §10.5).
  rows.push({ field: t("audit.exportLanguage"), value: t(`audit.language.${locale}` as const) });
  // Two-actor approval trail (Officer confirms → Reviewer approves).
  if (meta.officerConfirmedByName) rows.push({ field: t("audit.officerConfirmedBy"), value: meta.officerConfirmedByName });
  if (meta.officerConfirmedAt) rows.push({ field: t("audit.officerConfirmedAt"), value: fmtStamp(meta.officerConfirmedAt, locale) });
  if (meta.reviewedByName) rows.push({ field: t("audit.reviewedBy"), value: meta.reviewedByName });
  if (meta.reviewedByRole) rows.push({ field: t("audit.reviewerRole"), value: meta.reviewedByRole });
  if (meta.reviewedAt) rows.push({ field: t("audit.reviewedAt"), value: fmtStamp(meta.reviewedAt, locale) });
  if (meta.archivedAt) rows.push({ field: t("audit.archivedAt"), value: fmtStamp(meta.archivedAt, locale) });
  return rows;
}

// Real, openable, properly formatted PDF/Excel files generated from the
// report's own `content` (see reports.service.ts#generateContent) —
// RIO-NFR-007 (Arabic RTL) and the final bespoke per-report-type visual
// design are still a documented follow-up (the latter pending Karthika's
// Village Assessment Report viewer); this covers real pagination, section
// headings, and bordered tables generically today (RIO-NFR-008).
export async function buildExportStub(
  format: "pdf" | "excel",
  report: { id: string; title: string; reportType: string; content: Record<string, unknown> },
  meta: ExportAuditMeta,
  locale: AppLocale = DEFAULT_APP_LOCALE,
  /** English reference name -> the client's Arabic wording; see
   *  reference-names.ts. Empty for English exports and for a catalogue whose
   *  Arabic vocabulary has not been supplied yet. */
  referenceNames: Record<string, string> = {},
): Promise<{ filename: string; contentType: string; body: Buffer }> {
  const auditRows = auditMetaLines(meta, locale).map((r) => ({ label: r.field, value: r.value }));
  // Chrome is translated on the BUILT document rather than at each of
  // buildReportDoc's ~200 literal sites — see localise-doc.ts. That is also
  // what makes already-stored reports render in Arabic without regeneration.
  const doc = localiseReportDoc(
    { ...buildReportDoc(report.title, report.content, auditRows, locale), locale, rtl: isRtl(locale) },
    locale,
    referenceNames,
  );
  const ext = format === "pdf" ? "pdf" : "xlsx";
  // The locale is in the filename so two editions of one report do not collide
  // in a downloads folder — the previous name was identical for both, and the
  // second download would have been silently renamed by the browser.
  const filename = `${report.reportType}-${report.id}-${locale}.${ext}`;

  if (format === "pdf") {
    // Arabic goes to the Unicode renderer; English keeps the existing one
    // byte-for-byte. The old renderer maps every non-ASCII code point to "?",
    // so routing Arabic through it produced a page of question marks
    // (RIO-NFR-007, RIO-I18N-003 §6.3).
    const body = isRtl(locale) ? await renderReportPdfUnicode(doc) : renderReportPdf(doc);
    return { filename, contentType: "application/pdf", body };
  }
  return {
    filename,
    contentType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    body: await renderReportExcel(doc),
  };
}

// TODO(RIO-Reports-RPT13): canned executive-summary narrative pending real
// LLM/aggregation integration — same placeholder spirit as
// response-quality's generateAiSummary.
export function buildExecutiveSummaryNarrative(input: {
  studyTitle: string;
  priorityLevel: string | null;
  responseCount: number;
}): string {
  return (
    `Executive summary (placeholder) for "${input.studyTitle}". ` +
    `${input.responseCount} response(s) collected. ` +
    (input.priorityLevel
      ? `Current placeholder priority level: ${input.priorityLevel}.`
      : "Priority scoring has not yet been run for this study.")
  );
}

